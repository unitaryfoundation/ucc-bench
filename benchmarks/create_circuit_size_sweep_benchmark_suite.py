# This file is used to create a benchmark suite that is a parameter sweep in size
# over generated circuits. It is more convenient to do this in code than in a static
# TOML file, but we still use the TOML file to have a record of exactly what was run

# This script generates a parameter sweep benchmark suite for square_heisenberg and qft generators
# for sizes N = 4, 16, 64, 128, 256, 512, and writes it as a TOML file.

from pathlib import Path
from ucc_bench.suite import (
    BenchmarkSuite,
    CompilerSpec,
    BenchmarkSpec,
    GeneratorSpec,
)
from ucc_bench.registry import register
import tomlkit

# Output path for the new suite
target_path = Path(__file__).parent / "circuit_size_sweep_benchmarks.toml"


# Include all known compilers
compilers = [CompilerSpec(id=c) for c in register.get_compilers()]

sizes = [4, 16, 64, 121]

benchmarks = []
for N in sizes:
    for generator in register.get_generators():
        benchmarks.append(
            BenchmarkSpec(
                id=f"{generator}_N{N}",
                description=f"{generator} circuit (N={N})",
                generator=GeneratorSpec(name=generator, params={"N": N}),
            )
        )


suite = BenchmarkSuite(
    spec_version="1.0",
    suite_version="0.1",
    id="circuit_size_sweep_benchmarks",
    description="Sweep over circuit sizes for various circuit generators",
    compilers=compilers,
    benchmarks=benchmarks,
)

with open(target_path, "w") as f:
    f.write(f"# Auto-generated by {Path(__file__).name}\n")
    model_dict = suite.model_dump(
        exclude={"spec_path"},
        exclude_defaults=True,
        exclude_none=True,
        exclude_unset=True,
    )
    tomlkit.dump(model_dict, f)

print(f"Wrote parameter sweep suite to {target_path}")
